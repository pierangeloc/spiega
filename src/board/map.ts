/* ============================================================
   spiega map — the explanation seen from above.

   A chaptered board tells a reader where the parts are with a strip of tabs,
   and a strip of tabs is a list: it says there are four of them and says
   nothing about how they hang together. Someone who did not watch the
   explanation being drawn reads that as four unrelated pictures in a row.

   So the map: one card per chapter, in the order they were taught, with a
   line between the chapters that turn out to be about the same box. Those
   links are not declared anywhere — an explainer has enough to do — they are
   read back off what was drawn. If `release.yml` is on the board in chapter
   one and again in chapter three, those two chapters are about the same thing
   from two sides, and that is the sentence the map is trying to say.

   This file is loaded by the browser. No `node:` imports, ever — see the
   warning at the top of state.js.
   ============================================================ */

import type { Board, Chapter, Node } from './state.js';

/** One chapter, as the map shows it. */
export type MapCard = {
  /** Index into `board.chapters`, or null for the live one. */
  i: number | null,
  /** Its number on the strip, counting from 1. */
  n: number,
  title: string,
  live: boolean,
  nodes: number,
  edges: number,
  steps: number,
  /** The first thing said in it, which is usually its thesis. */
  line: string,
};

/**
 * Two chapters, and why they are joined. `shared` is the boxes both of them
 * draw, in the order the earlier chapter drew them; empty for the plain
 * `then` of one chapter following another.
 */
export type MapLink = {
  /** A card's `n`. */
  from: number,
  to: number,
  shared: string[],
};

export type BoardMap = { cards: MapCard[], links: MapLink[] };

type Surface = Chapter | Board;

/* Two boxes are the same box when they read as the same box. Ids are per
   chapter and often autogenerated, so the label is what carries the identity
   — and it is matched loosely, because the same thing gets written
   `release.yml` once and `release.yml ` the next time, or capitalised
   differently by an agent that had stopped thinking about ids by then. */
const key = (node: Node): string => String(node.label || node.id || '')
  .toLowerCase().replace(/[`'"*]/g, '').replace(/\s+/g, ' ').trim();

/* The boxes a chapter is about: what it drew, less its notes. A note is
   prose that happens to be in a box, and two chapters carrying the same
   sticky note are not two views of one thing. */
const boxes = (surface: Surface): Map<string, string> => {
  const out = new Map<string, string>();
  for (const n of surface.nodes || []) {
    if (n.kind === 'note') continue;
    const k = key(n);
    if (k && !out.has(k)) out.set(k, String(n.label || n.id));
  }
  return out;
};

/**
 * The whole explanation at a glance: every chapter, and the links between the
 * ones that share a box. The live chapter is a card like any other — it is
 * where the explainer is standing, and a map that left it out would be a map
 * of everywhere the reader is not.
 */
export function boardMap(board: Board | null | undefined): BoardMap {
  if (!board) return { cards: [], links: [] };
  const all: { surface: Surface, card: MapCard }[] = [];
  /* The live chapter's name is `board.chapter`; `board.title` names the whole
     explanation and would put the board's own heading on one card. */
  const push = (surface: Surface, i: number | null, live: boolean, title: string) => {
    all.push({
      surface,
      card: {
        i, n: all.length + 1,
        title: title || (live ? 'being drawn' : 'untitled'),
        live,
        nodes: (surface.nodes || []).length,
        edges: (surface.edges || []).length,
        steps: (surface.flow || []).length,
        line: (surface.transcript || [])[0]?.text || '',
      },
    });
  };
  (board.chapters || []).forEach((c, i) => push(c, i, false, c.title));
  push(board, null, true, board.chapter);

  const drawn = all.map(({ surface }) => boxes(surface));
  const links: MapLink[] = [];
  for (let a = 0; a < all.length; a++) {
    for (let b = a + 1; b < all.length; b++) {
      const shared = [...drawn[a].entries()]
        .filter(([k]) => drawn[b].has(k))
        .map(([, label]) => label);
      if (shared.length) links.push({ from: a + 1, to: b + 1, shared });
    }
  }
  /* Chapters that share nothing still follow one another, and a map with one
     island per chapter would be a worse tab strip. The plain `then` is drawn
     only where there is no shared box to draw instead: two lines between the
     same pair say one thing twice, and the weaker one wins the eye. */
  for (let a = 0; a + 1 < all.length; a++) {
    if (!links.some(l => l.from === a + 1 && l.to === a + 2)) {
      links.push({ from: a + 1, to: a + 2, shared: [] });
    }
  }
  links.sort((p, q) => p.from - q.from || p.to - q.to);
  return { cards: all.map(c => c.card), links };
}

/* A box's label is written to be read inside the box: it runs to two lines and
   is as long as `css_fulfilled_orders`. On the map it has to survive as a pill
   floating over the drawing, so it gets one line and a budget, and loses its
   tail to an ellipsis we put there rather than one the browser clips mid-word. */
const short = (label: string, max = 28): string => {
  const first = String(label).split('\n')[0].trim();
  return first.length > max
    ? `${first.slice(0, max - 1).replace(/[\s_\-.,:;/]+$/, '')}…`
    : first;
};

/* What a link says on the map. One name reads as a fact and two already read
   as a list, so only the first is named and the rest are counted — the pill is
   there to say *which* box the two chapters share, not to inventory them. */
export const linkLabel = (link: MapLink): string =>
  !link.shared.length ? 'then'
    : link.shared.length === 1 ? short(link.shared[0])
      : `${short(link.shared[0])} +${link.shared.length - 1}`;
