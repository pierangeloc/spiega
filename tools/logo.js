#!/usr/bin/env node
/* ============================================================
   Logo candidates, drawn with the product's own ink.

   An icon for this project has been attempted before and failed four times
   (issue #2), and what those attempts established is that inventing the
   coordinates of a hand by eye does not work: a few percent off and it is a
   different object. The way out is not to try harder, it is to stop drawing
   by hand.

   So these are generated by `src/render/ink.js` — the same waver, the same
   seeded wobble, the same palette the board uses. The hand-drawn quality is
   therefore the real one rather than my imitation of it, and a candidate is
   a handful of geometry rather than a page of path data nobody can edit.

   Every candidate must survive 16px. That is the whole test: at a browser
   tab's size, detail is not small, it is absent. Run this, then open the
   contact sheet it prints and look at the first column.

     node tools/logo.js            write docs/logo/*.svg + the contact sheet
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { roughRect, roughLine, roughPoly, stroke, fill, waver, smooth } from '../src/render/ink.js';
import { PAPER, INK, ACCENT, SHADOW, MUTED } from '../src/render/theme.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '..', 'docs', 'logo');

const W = 64;                       // the grid everything is drawn on
const svg = (body, { bg = null } = {}) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${W}" width="${W}" height="${W}">` +
  (bg ? `<rect width="${W}" height="${W}" rx="12" fill="${bg}"/>` : '') +
  body + '</svg>';

/* ---------- the candidates ----------

   Judged on the 16px column and nothing else.

   Three things have been dropped across two sheets, and the third is the one
   worth recording. Two boxes and a line read as "oo" at 16px. A half-drawn box
   was an ambiguous hook. And a pen — drawn twice, once small and once large
   — never read as a pen: at the sizes that matter it is a dark speck beside a
   dark stroke, or a blob in a corner. That is the same failure as the hand in
   issue #2, and the same conclusion: this is not a mark that can carry a
   recognisable object. What survives is a stroke, a frame, and a letter. */

const make = ({ ink = INK, ground = null }) => ({
  /* The brief, minus the hand: a board with a stroke on it. The stroke is the
     writing; the frame is the board. Two shapes, both large. */
  'board-and-stroke': () =>
    svg(stroke(roughRect(5, 11, 54, 42, 8, { seed: 5, amp: 0.9 }), { w: 4.4, color: ink }) +
      stroke(smooth(waver([[15, 36], [30, 27], [45, 33]], { seed: 9, amp: 1.6, step: 7 }), false),
        { w: 6, color: ACCENT }),
      { bg: ground }),

  /* Talking becoming structure: a free stroke on the left that has turned
     into a drawn box on the right. The closest of these to what the tool
     actually does. */
  'stroke-to-box': () =>
    svg(stroke(smooth(waver([[5, 38], [17, 33], [26, 31]], { seed: 3, amp: 1.6, step: 8 }), false),
      { w: 5.5, color: ACCENT }) +
      stroke(roughRect(27, 17, 31, 30, 7, { seed: 11, amp: 1.1 }), { w: 5, color: ink }),
      { bg: ground }),

  /* The initial, written rather than set. One shape, which is the best answer
     there is to the 16px problem, and the only candidate legible at 16 on the
     first sheet. The accent mark is where the stroke ends. */
  'written-s': () =>
    svg(stroke(smooth(waver([[46, 17], [26, 13], [19, 24], [34, 32], [46, 41], [36, 52], [16, 47]],
      { seed: 13, amp: 1.2, step: 9 }), false), { w: 6, color: ink }) +
      fill(smooth([[13, 44], [19, 46], [15, 52]], true), ACCENT),
      { bg: ground }),
});

/* Each one twice: ink on paper, and paper on ink. A logo that works on only
   one ground is half a logo — every mark on the first sheet vanished against
   a dark background. */
const candidates = {};
for (const [name, fn] of Object.entries(make({}))) candidates[name] = fn;
for (const [name, fn] of Object.entries(make({ ink: PAPER, ground: INK }))) {
  candidates[`${name}-dark`] = fn;
}

/* ---------- write them, and a sheet to judge them by ---------- */

fs.mkdirSync(OUT, { recursive: true });
const names = Object.keys(candidates);
for (const name of names) fs.writeFileSync(path.join(OUT, `${name}.svg`), candidates[name]());

const SIZES = [16, 24, 32, 48, 96];
const sheet = `<!doctype html><meta charset="utf-8"><title>spiega logo candidates</title>
<style>
  body{background:${PAPER};color:${INK};font:13px ui-monospace,Menlo,monospace;padding:28px 32px}
  h1{font-size:14px;letter-spacing:.14em;text-transform:uppercase;color:${MUTED};font-weight:700}
  table{border-collapse:collapse;margin-top:18px}
  td,th{padding:12px 16px;text-align:center;vertical-align:middle}
  th{font-size:10px;letter-spacing:.1em;color:${MUTED};text-transform:uppercase}
  td.name{text-align:left;font-weight:700}
  tr+tr{border-top:1px solid ${SHADOW}22}
  .dark{background:${INK};border-radius:8px}
  img{display:block}
</style>
<h1>spiega — logo candidates</h1>
<p style="color:${MUTED};max-width:52ch">The first column is the only one that
matters. A mark that does not survive 16px is not a logo, it is an illustration.</p>
<table>
<tr><th>name</th>${SIZES.map(s => `<th>${s}px</th>`).join('')}<th>on ink</th></tr>
${names.map(n => `<tr><td class="name">${n}</td>` +
  SIZES.map(s => `<td><img src="${n}.svg" width="${s}" height="${s}"></td>`).join('') +
  `<td class="dark"><img src="${n}.svg" width="48" height="48"></td></tr>`).join('\n')}
</table>`;
fs.writeFileSync(path.join(OUT, 'index.html'), sheet);

console.log(`${names.length} candidates → ${path.relative(process.cwd(), OUT)}/`);
for (const n of names) console.log(`  ${n}.svg`);
console.log(`\nopen ${path.relative(process.cwd(), path.join(OUT, 'index.html'))}`);
