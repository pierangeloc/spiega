#!/usr/bin/env node
/* ============================================================
   spiega regressions — the boards that were wrong, next to what they
   look like now.

   The pictures in docs/regressions are committed so that a change to the
   renderer shows up as a diff of a drawing rather than a diff of XML. That
   works while a board's wrong version and its right one are two commits on
   the same file — and it stops working the moment a pull request is squashed,
   because the wrong version was only ever an intermediate commit and the
   squash throws it away. The first time it mattered, the before-and-after that
   the gallery existed to produce survived only as a URL into a closed PR.

   So the comparison does not live in the history. Both pictures are in the
   tree: <board>-before.svg is frozen at the state the bug was reported in and
   is never regenerated, <board>.svg is current and is regenerated like every
   other picture here. This page sets them side by side. Nothing about it
   depends on how anything was merged.

   Run `node tools/regressions.js`. It writes docs/regressions.md.
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOARDS = path.join(ROOT, 'test/boards');
const PICS = path.join(ROOT, 'docs/regressions');
const OUT = path.join(ROOT, 'docs/regressions.md');
const REPO = 'https://github.com/pierangeloc/spiega/issues';

const manifest = JSON.parse(fs.readFileSync(path.join(BOARDS, 'manifest.json'), 'utf8'));

const names = fs.readdirSync(BOARDS)
  .filter(f => f.endsWith('.json') && f !== 'manifest.json')
  .map(f => f.replace(/\.json$/, ''))
  .sort();

/* A board with no frozen before is one whose bug is still open: there is
   nothing to compare it against yet, and its single picture is the bug. */
const rows = names.map(name => {
  const spec = JSON.parse(fs.readFileSync(path.join(BOARDS, `${name}.json`), 'utf8'));
  return {
    name, spec,
    m: manifest[name] || {},
    before: fs.existsSync(path.join(PICS, `${name}-before.svg`)) ? `regressions/${name}-before.svg` : null,
    after: `regressions/${name}.svg`,
  };
});

const missing = rows.filter(r => !manifest[r.name]).map(r => r.name);
if (missing.length) {
  console.error(`these boards are not described in test/boards/manifest.json:\n  ${missing.join('\n  ')}`);
  process.exit(1);
}

const link = src => `<a href="${src}"><img src="${src}" width="420"></a>`;

const out = [];
out.push('# The boards that were wrong');
out.push('');
out.push('Every rendering bug that has been reported keeps its spec in `test/boards/`');
out.push('and its picture here. The left-hand drawing is frozen at the state the bug was');
out.push('reported in. The right-hand one is regenerated from the current renderer every');
out.push('time the suite runs, so it cannot quietly stop matching the code.');
out.push('');
out.push('This page is generated by `node tools/regressions.js`. Do not edit it by hand.');
out.push('');

for (const r of rows) {
  const title = r.spec.title || r.name;
  out.push(`## ${title}`);
  out.push('');
  out.push(`[#${r.m.issue}](${REPO}/${r.m.issue}) · \`test/boards/${r.name}.json\``);
  out.push('');
  out.push(`**What was wrong.** ${r.m.broke}`);
  out.push('');
  if (r.before) {
    out.push(`**What changed.** ${r.m.fixed}`);
    out.push('');
    out.push('| as reported | now |');
    out.push('| --- | --- |');
    /* Side by side the pair shows the shape of the change; the detail that was
       the bug is often a few pixels of a label, so each one opens full size. */
    out.push(`| ${link(r.before)} | ${link(r.after)} |`);
  } else {
    out.push('**Still open.** This is what it draws today.');
    out.push('');
    out.push(link(r.after));
  }
  out.push('');
}

fs.writeFileSync(OUT, out.join('\n'));
console.log(path.relative(ROOT, OUT));
for (const r of rows)
  console.log(`  ${r.name}  ${r.before ? 'before + now' : 'open, one picture'}`);
